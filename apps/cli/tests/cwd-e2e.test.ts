describe('working directory through the command', () => {
  test('a later command runs in the directory the model moved to', async () => {
    const root = await mkdtemp(join(tmpdir(), 'jozo-harness-cwd-'))
    const workspace = await mkdtemp(join(tmpdir(), 'jozo-harness-ws-'))
    const sub = join(workspace, 'sub')
    await mkdir(sub, { recursive: true })

    const code = await Effect.runPromise(
      runCommand({
        profiles: [profile(root)],
        plugins: [
          kernelPlugin,
          sessionJsonlPlugin,
          sessionPlugin,
          toolsPlugin,
          systemPromptPlugin,
          safetyPlugin,
          askPlugin,
          tier0Plugin,
          tier1Plugin,
          stubLlm,
          agentPlugin,
          agentLoopPlugin,
        ] as ReadonlyArray<Plugin<any, any, any>>,
        cwd: workspace,
        route: 'stub/model',
        task: 'look in sub',
        stdout: () => undefined,
        stderr: () => undefined,
      }),
    )
    expect(code).toBe(0)

    const sessions = await Effect.runPromise(jsonlSessions({ root }).list())
    const opened = await Effect.runPromise(jsonlSessions({ root }).open(sessions[0]?.id ?? ''))
    const types = opened.events.map((event) => event.type)
    const results = opened.events.filter((event) => event.type === 'tool/result')

    expect(types).toContain('session/cwd/changed')
    expect(results).toHaveLength(2)
    expect(JSON.stringify(results[1]?.data.content)).toContain(sub)
    await rm(root, { recursive: true, force: true })
    await rm(workspace, { recursive: true, force: true })
  })
})
