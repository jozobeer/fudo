describe('skill through the command', () => {
  test('the skill body reaches the model as the tool result', async () => {
    const root = await mkdtemp(join(tmpdir(), 'jozo-harness-skill-'))
    const skills = await mkdtemp(join(tmpdir(), 'jozo-harness-skills-'))
    const MARKER = 'SKILL-BODY-MARKER'
    await writeFileDeep(
      join(skills, 'demo', 'SKILL.md'),
      '---\nname: demo\ndescription: Steps for the demo\n---\n\n' + MARKER + '\nstep one\n',
    )

    const code = await Effect.runPromise(
      runCommand({
        profiles: [profile(root)],
        plugins: [
          kernelPlugin,
          sessionJsonlPlugin,
          sessionPlugin,
          toolsPlugin,
          systemPromptPlugin,
          safetyPlugin,
          askPlugin,
          tier1Plugin,
          stubLlm,
          agentPlugin,
          agentLoopPlugin,
        ] as ReadonlyArray<Plugin<any, any, any>>,
        cwd: '/tmp',
        route: 'stub/model',
        task: 'use the demo skill',
        skills: [skills],
        stdout: () => undefined,
        stderr: () => undefined,
      }),
    )
    expect(code).toBe(0)

    const sessions = await Effect.runPromise(jsonlSessions({ root }).list())
    const opened = await Effect.runPromise(jsonlSessions({ root }).open(sessions[0]?.id ?? ''))
    const result = opened.events.find((event) => event.type === 'tool/result')

    expect(result?.type === 'tool/result' ? result.data.isError : true).toBe(false)
    expect(JSON.stringify(result)).toContain(MARKER)
    await rm(root, { recursive: true, force: true })
    await rm(skills, { recursive: true, force: true })
  })
})
